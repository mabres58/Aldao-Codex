import { test } from 'node:test';
import assert from 'node:assert/strict';
import { seedIfEmpty, STORAGE_KEYS } from '../src/lib/storage.ts';
import { readRequests } from '../src/lib/requests.ts';
import { employees } from '../src/lib/seed.ts';
import { startSession } from '../src/lib/session.ts';
import { countRequests, EMPTY_FILTERS, filterRequests, findConflicts, pendingRequests, resolvedRequests, resolveRequest } from '../src/lib/admin.ts';
const data = new Map<string,string>();
let blocked = false;
Object.defineProperty(globalThis,'localStorage',{configurable:true,value:{getItem:(key:string)=>data.get(key) ?? null,setItem:(key:string,value:string)=>{if(blocked) throw new Error('Cuota excedida');data.set(key,value);},removeItem:(key:string)=>data.delete(key)}});
function rows() {const result = readRequests();assert.ok(result.ok);return result.value;}
test('indicadores, orden y filtros simultáneos por empleado, tipo y fecha',()=>{
  seedIfEmpty();
  const initial = rows();
  assert.deepEqual(countRequests(initial),{Pendiente:8,Aprobada:2,Rechazada:2});
  assert.equal(filterRequests(initial,EMPTY_FILTERS).length,12);
  const filter = {employeeId:'e1',tipo:'Horas extra',fecha:initial[10].fecha};
  const filtered = filterRequests(initial,filter);
  assert.equal(filtered.length,1);
  assert.equal(pendingRequests(filtered).length,0);
  assert.equal(resolvedRequests(filtered)[0].id,'s11');
  assert.equal(filterRequests(initial,{...filter,fecha:'2000-01-01'}).length,0);
  const pending = pendingRequests(initial);
  assert.ok(pending.every((row,index)=>index === 0 || pending[index-1].fecha <= row.fecha));
});
test('coincidencias: misma área, distinta área, aprobadas, rechazo, mismo empleado y fecha distinta',()=>{
  const initial = rows();
  const source = initial[6];
  const conflicts = findConflicts(source,initial,employees);
  assert.equal(conflicts.length,1);assert.equal(conflicts[0].employee?.id,'e8');assert.equal(conflicts[0].sameArea,true);
  const approved = {...initial[7],estado:'Aprobada' as const};
  assert.equal(findConflicts(source,[source,approved],employees).length,1);
  const otherArea = {...approved,employeeId:'e2'};
  assert.equal(findConflicts(source,[source,otherArea],employees)[0].sameArea,false);
  assert.equal(findConflicts(source,[source,{...approved,estado:'Rechazada'}],employees).length,0);
  assert.equal(findConflicts(source,[source,{...approved,employeeId:'e7'}],employees).length,0);
  assert.equal(findConflicts(source,[source,{...approved,fecha:'2000-01-01'}],employees).length,0);
  assert.equal(findConflicts(initial[0],initial,employees).length,0);
});
test('resolución relee storage, persiste, bloquea el segundo intento sin cambiar estado ni timestamp',()=>{
  startSession({rol:'admin',employeeId:null,timestamp:new Date().toISOString()});
  const first = resolveRequest('s1','Aprobada');assert.ok(first.ok);
  const approved = rows().find(row=>row.id === 's1')!;
  assert.equal(approved.estado,'Aprobada');assert.ok(approved.fechaResolucion);
  const snapshot = data.get(STORAGE_KEYS.requests);
  const repeated = resolveRequest('s1','Rechazada');
  assert.equal(repeated.ok,false);
  if(!repeated.ok) assert.equal(repeated.error,'Esta solicitud ya fue resuelta.');
  assert.equal(data.get(STORAGE_KEYS.requests),snapshot);
  assert.equal(resolveRequest('s2','Rechazada').ok,true);
  assert.deepEqual(countRequests(rows()),{Pendiente:6,Aprobada:3,Rechazada:3});
  const history = resolvedRequests(rows());
  assert.ok(history.slice(0,2).every(row=>['s1','s2'].includes(row.id)));
  blocked = true;
  const before = data.get(STORAGE_KEYS.requests);
  assert.equal(resolveRequest('s3','Aprobada').ok,false);
  assert.equal(data.get(STORAGE_KEYS.requests),before);
  blocked = false;
  startSession({rol:'empleado',employeeId:'e1',timestamp:new Date().toISOString()});
  assert.equal(resolveRequest('s3','Aprobada').ok,false);
});

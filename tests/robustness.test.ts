import { test } from 'node:test';
import assert from 'node:assert/strict';
import { setItem, getStorageStatus, setSimulatedBlocked, seedIfEmpty, STORAGE_KEYS, subscribeData, handleStorageEvent } from '../src/lib/storage.ts';
import { startSession, readSession, SESSION_KEY } from '../src/lib/session.ts';
import { resolveRequestSafely } from '../src/lib/admin.ts';
const data = new Map<string,string>();
let writes = 0;
Object.defineProperty(globalThis,'localStorage',{configurable:true,value:{getItem:(key:string)=>data.get(key) ?? null,setItem:(key:string,value:string)=>{writes++;data.set(key,value);},removeItem:(key:string)=>data.delete(key)}});
test('bloqueo no persiste ni escribe; una escritura posterior recupera el estado ok',()=>{
  seedIfEmpty();
  const before = new Map(data);
  setSimulatedBlocked(true);
  assert.equal(setItem(STORAGE_KEYS.requests,[]).ok,false);
  assert.equal(getStorageStatus(),'error');
  assert.deepEqual(data,before);
  setSimulatedBlocked(false);
  assert.equal(getStorageStatus(),'error');
  assert.equal(setItem('test-only','ok').ok,true);
  assert.equal(getStorageStatus(),'ok');
  data.delete('test-only');
});
test('solo eventos externos de datos notifican, cambios de sesión no fuerzan cierre local',()=>{
  let calls = 0;
  const stop = subscribeData(()=>{calls++;});
  const timestamp = new Date().toISOString();
  startSession({rol:'admin',employeeId:null,timestamp});
  const stored = data.get(STORAGE_KEYS.requests);
  setItem(STORAGE_KEYS.requests,JSON.parse(stored!));
  assert.equal(calls,0);
  handleStorageEvent({key:STORAGE_KEYS.requests,storageArea:null});
  handleStorageEvent({key:STORAGE_KEYS.employees,storageArea:null});
  assert.equal(calls,2);
  data.delete(SESSION_KEY);
  handleStorageEvent({key:SESSION_KEY,storageArea:null});
  assert.equal(calls,2);
  assert.equal(readSession()?.rol,'admin');
  handleStorageEvent({key:null,storageArea:null});
  assert.equal(calls,3);
  stop();
});
test('intentos simultáneos, tardíos y desmontados no producen segunda escritura',async()=>{
  const before = writes;
  const results = await Promise.all([resolveRequestSafely('s1','Aprobada'),resolveRequestSafely('s1','Rechazada')]);
  assert.equal(results.filter(row=>row.ok).length,1);
  assert.equal(writes,before+1);
  const snapshot = data.get(STORAGE_KEYS.requests);
  const repeated = await resolveRequestSafely('s1','Rechazada');
  assert.equal(repeated.ok,false);
  if(!repeated.ok) assert.equal(repeated.error,'Esta solicitud ya fue resuelta.');
  await resolveRequestSafely('s2','Aprobada',()=>false);
  assert.equal(writes,before+1);
  assert.equal(data.get(STORAGE_KEYS.requests),snapshot);
});
